function Log {
    param([string]$Line = '')
    Write-Host $Line
    $resultLines.Add($Line)
}

function LogSeparator { Log ('─' * 72) }

function New-Uuid { return [System.Guid]::NewGuid().ToString() }

function Invoke-ApiRequest {
    param(
        [string]$Method,
        [string]$Url,
        [hashtable]$Headers = @{},
        [object]$Body = $null,
        [string]$ContentType = 'application/json'
    )

    $iwrParams = @{
        Method             = $Method
        Uri                = $Url
        Headers            = $Headers
        SkipCertificateCheck = $true
        UseBasicParsing    = $true
        ErrorAction        = 'Stop'
    }

    if ($null -ne $Body) {
        $iwrParams['Body']        = ($Body | ConvertTo-Json -Depth 10 -Compress)
        $iwrParams['ContentType'] = $ContentType
    }

    try {
        $response = Invoke-WebRequest @iwrParams
        return @{
            StatusCode = [int]$response.StatusCode
            Body       = $response.Content
            Error      = $null
            Response   = $response
        }
    } catch [System.Net.WebException] {
        $sc = [int]$_.Exception.Response.StatusCode
        $body = ''
        try {
            $reader = New-Object System.IO.StreamReader($_.Exception.Response.GetResponseStream())
            $body = $reader.ReadToEnd()
        } catch {}
        return @{
            StatusCode = $sc
            Body       = $body
            Error      = $_.Exception.Message
            Response   = $null
        }
    } catch {
        return @{
            StatusCode = 0
            Body       = ''
            Error      = $_.Exception.Message
            Response   = $null
        }
    }
}

function Record-TestResult {
    param(
        [int]    $TestNum,
        [string] $TestName,
        [string] $Expected,
        [int]    $ActualStatus,
        [bool]   $Passed,
        [string] $Notes = ''
    )

    $ts     = Get-Date -Format 'HH:mm:ss'
    $result = if ($Passed) { 'PASS' } else { 'FAIL' }
    $color  = if ($Passed) { 'Green' } else { 'Red' }
    $line   = "  [$result] Test $($TestNum.ToString().PadLeft(2,'0')): $TestName"
    $detail = "           Expected: $Expected | Actual status: $ActualStatus | $ts"

    Write-Host $line -ForegroundColor $color
    Write-Host $detail
    if ($Notes) { Write-Host "           Notes: $Notes" -ForegroundColor Gray }
    Log $line
    Log $detail
    if ($Notes) { Log "           Notes: $Notes" }

    $testResults.Add(@{
        Num      = $TestNum
        Name     = $TestName
        Expected = $Expected
        Actual   = $ActualStatus
        Passed   = $Passed
        Notes    = $Notes
    })
}

