        -BaseUrl 'https://hcrf.example.com' `
        -TestRecordId 'clxxxxxxxxxxxxxxxx'

.PARAMETER TestRecordId
    The designated production test record ID (SkcStakeholderRegistration.id).
    This record MUST be pre-approved for smoke test classification in production.

.EXAMPLE
    .\production-smoke-test.ps1 `
        -BaseUrl 'https://hcrf.example.com' `
